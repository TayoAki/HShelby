import { z } from "zod";
import { AiConversation } from "./ai";
import { LocalAppearance } from "./appearance";
import { DeviceSubscription } from "./subscriptions";
import { InboxCard, MessageKind, ReportedPaywall, ReportedPaywalls, SdkCard } from "./cards";
import { IdentityLabels, IdentityToken, Metadata, SdkIdentity } from "./identity";
import { Attachment, PHOTO_LIMITS } from "./photos";
import { DevicePush, PushRegistration } from "./push";

/* ---------- shared ---------- */

export const MESSAGE_MAX_LENGTH = 4000;

export const MessageSender = z.enum(["user", "agent"]);
export type MessageSender = z.infer<typeof MessageSender>;

export const ConversationStatus = z.enum(["open", "closed"]);
export type ConversationStatus = z.infer<typeof ConversationStatus>;

/**
 * A new message: text, photos (uploaded first, see `UploadRequest`), or both. `clientId` is generated by the
 * sender; resending with the same one never duplicates.
 */
export const SendMessageInput = z
  .object({
    clientId: z.uuid(),
    text: z.string().trim().max(MESSAGE_MAX_LENGTH).default(""),
    attachmentIds: z.array(z.uuid()).max(PHOTO_LIMITS.perMessage).default([]),
  })
  .strict()
  .refine((m) => m.text.length > 0 || m.attachmentIds.length > 0, { message: "send text, a photo, or both" })
  .refine((m) => new Set(m.attachmentIds).size === m.attachmentIds.length, { message: "attachmentIds repeat" });
export type SendMessageInput = z.infer<typeof SendMessageInput>;

export const ReadInput = z.object({ seq: z.number().int().min(0) }).strict();
export type ReadInput = z.infer<typeof ReadInput>;

const seqParam = (min: number) => z.coerce.number().int().min(min).optional();

/** Message paging: `after` for polling and catch-up, `before` for older history, neither for the latest page. */
export const MessagePageQuery = z.object({
  after: seqParam(0),
  before: seqParam(1),
  limit: z.coerce.number().int().min(1).max(100).optional(),
});
export type MessagePageQuery = z.infer<typeof MessagePageQuery>;

/* ---------- SDK (/v1) ---------- */

export const DeviceDetails = z
  .object({
    model: z.string().trim().max(100),
    osVersion: z.string().trim().max(50),
    appVersion: z.string().trim().max(50),
    sdkVersion: z.string().trim().max(50),
    locale: z.string().trim().max(35),
    timezone: z.string().trim().max(64),
  })
  .partial()
  .strict();
export type DeviceDetails = z.infer<typeof DeviceDetails>;

/** What registration and later updates can carry besides the App ID. Each part is optional. */
const DeviceState = {
  device: DeviceDetails.optional(),
  identity: IdentityLabels.optional(),
  identityToken: IdentityToken.optional(),
  metadata: Metadata.optional(),
  /** null clears the token (e.g. notifications were turned off). */
  push: PushRegistration.nullable().optional(),
  /** The paywalls the app can show right now (phase B7); offers can only name these. */
  paywalls: ReportedPaywalls.optional(),
  /** The app's own appearance settings (phase B9), where the dashboard's design editor starts. */
  appearance: LocalAppearance.optional(),
  /**
   * What StoreKit says on the device (phase B10): whether the person pays, and the original transaction IDs of
   * their subscriptions, which match App Store Server Notifications to them. IDs are kept across reports.
   */
  storekit: z
    .object({
      paying: z.boolean(),
      originalTransactionIds: z.array(z.string().regex(/^\d{1,20}$/)).max(20),
    })
    .partial()
    .strict()
    .optional(),
};

export const RegisterDeviceInput = z
  .object({ appId: z.string().regex(/^app_[0-9A-Za-z]{22}$/), ...DeviceState })
  .strict();
export type RegisterDeviceInput = z.infer<typeof RegisterDeviceInput>;

/** `PATCH /v1/device`: the SDK's staged state. Atomic: if the identity token is rejected, nothing changes. */
export const DeviceUpdateInput = z.object(DeviceState).strict();
export type DeviceUpdateInput = z.infer<typeof DeviceUpdateInput>;

export const DeviceUpdateResult = z.object({ identity: SdkIdentity });
export type DeviceUpdateResult = z.infer<typeof DeviceUpdateResult>;

export const AccessToken = z.object({ accessToken: z.string(), expiresIn: z.number().int() });
export type AccessToken = z.infer<typeof AccessToken>;

/** Returned once at registration. The SDK stores `deviceSecret` in the Keychain and refreshes tokens with it. */
export const DeviceSession = AccessToken.extend({ deviceSecret: z.string(), identity: SdkIdentity });
export type DeviceSession = z.infer<typeof DeviceSession>;

export const RefreshInput = z.object({ deviceSecret: z.string().min(1).max(200) }).strict();
export type RefreshInput = z.infer<typeof RefreshInput>;

export const SdkMessage = z.object({
  id: z.string(),
  seq: z.number().int(),
  sender: MessageSender,
  kind: MessageKind,
  text: z.string(),
  /** Set on review and offer messages. */
  card: SdkCard.nullable(),
  /** The first tap on the card's button. */
  actionClickedAt: z.string().nullable(),
  /**
   * The teammate behind a reply, as far as the app shows it (phase B9): a first name with "Show team names", a
   * temporary photo link with "Show team photos" (and the initial when there's no photo). Null otherwise.
   */
  author: z.object({ name: z.string().nullable(), initial: z.string().nullable(), photoUrl: z.string().nullable() }).nullable(),
  /** Written by the AI (phase B11), so the chat can label it. */
  byAi: z.boolean(),
  /** Set on the device's own messages, so the SDK can match them to its pending sends. */
  clientId: z.string().nullable(),
  attachments: z.array(Attachment),
  createdAt: z.string(),
});
export type SdkMessage = z.infer<typeof SdkMessage>;

export const SdkConversation = z.object({
  id: z.string(),
  status: ConversationStatus,
  lastSeq: z.number().int(),
  userReadSeq: z.number().int(),
  unread: z.number().int(),
});
export type SdkConversation = z.infer<typeof SdkConversation>;

/** Whether the device may send, and why not: the SDK shows "Sign in to send messages." for verification_required. */
export const SdkSending = z.object({
  allowed: z.boolean(),
  reason: z.enum(["device_blocked", "verification_required"]).nullable(),
});
export type SdkSending = z.infer<typeof SdkSending>;

/** `GET /v1/conversation`: `conversation` is null until the device sends its first message. */
export const SdkSync = z.object({
  identity: SdkIdentity,
  sending: SdkSending,
  conversation: SdkConversation.nullable(),
  messages: z.array(SdkMessage),
  hasMore: z.boolean(),
});
export type SdkSync = z.infer<typeof SdkSync>;

export const SdkSendResult = z.object({ message: SdkMessage, conversation: SdkConversation });
export type SdkSendResult = z.infer<typeof SdkSendResult>;

export const Unread = z.object({ unread: z.number().int() });
export type Unread = z.infer<typeof Unread>;

/* ---------- dashboard inbox (/api) ---------- */

export const InboxDevice = z.object({
  id: z.string(),
  model: z.string().nullable(),
  osVersion: z.string().nullable(),
  appVersion: z.string().nullable(),
  sdkVersion: z.string().nullable(),
  locale: z.string().nullable(),
  timezone: z.string().nullable(),
  blocked: z.boolean(),
  lastSeenAt: z.string().nullable(),
  createdAt: z.string(),
  userId: z.string().nullable(),
  name: z.string().nullable(),
  email: z.string().nullable(),
  /** True when the identity came from a valid token; labels alone are "Unverified". */
  verified: z.boolean(),
  verifiedAt: z.string().nullable(),
  metadata: z.record(z.string(), z.string()),
  /** The user logged out of this device: replies stay in the history but won't reach them. */
  signedOutAt: z.string().nullable(),
  push: DevicePush,
  /** The chat is open in the app right now (phase B6). */
  inChat: z.boolean(),
  /** When the user last had the chat open. */
  lastSeenInChatAt: z.string().nullable(),
  /** What "Send offer" can choose from: the paywalls the device last reported, and when (phase B7). */
  paywalls: z.array(ReportedPaywall),
  paywallsReportedAt: z.string().nullable(),
  /** When the team last asked this device for a review. */
  reviewAskedAt: z.string().nullable(),
  /** The subscription as the provider last reported it (phase B10). */
  subscription: DeviceSubscription.nullable(),
});
export type InboxDevice = z.infer<typeof InboxDevice>;

export const InboxConversation = z.object({
  id: z.string(),
  status: ConversationStatus,
  app: z.object({ id: z.string(), name: z.string(), iconUrl: z.string().nullable() }),
  device: InboxDevice,
  lastSeq: z.number().int(),
  unreadForTeam: z.number().int(),
  lastMessageAt: z.string(),
  lastMessage: z.object({ sender: MessageSender, text: z.string() }).nullable(),
  /** The app's setup conversation (its first, from the developer's test device): replies work here without a subscription. */
  setup: z.boolean(),
  /** Whether the AI answers here (phase B11); null when the app's AI replies are off. */
  ai: AiConversation.nullable(),
});
export type InboxConversation = z.infer<typeof InboxConversation>;

export const InboxListQuery = z.object({
  status: z.enum(["open", "closed", "all"]).default("open"),
  appId: z.uuid().optional(),
  /** Matches name, email, user ID or the latest message, case-insensitively. */
  q: z.string().trim().max(100).optional(),
  cursor: z.string().max(200).optional(),
  limit: z.coerce.number().int().min(1).max(100).default(30),
});
export type InboxListQuery = z.infer<typeof InboxListQuery>;

export const InboxList = z.object({
  conversations: z.array(InboxConversation),
  nextCursor: z.string().nullable(),
});
export type InboxList = z.infer<typeof InboxList>;

export const InboxMessage = z.object({
  id: z.string(),
  seq: z.number().int(),
  sender: MessageSender,
  source: z.enum(["sdk", "dashboard", "telegram", "automation", "ai"]),
  kind: MessageKind,
  text: z.string(),
  card: InboxCard.nullable(),
  actionClickedAt: z.string().nullable(),
  /** Set on teammates' messages, so the dashboard can match a sent reply to its optimistic copy. */
  clientId: z.string().nullable(),
  attachments: z.array(Attachment),
  createdAt: z.string(),
  author: z.object({ id: z.string(), name: z.string() }).nullable(),
});
export type InboxMessage = z.infer<typeof InboxMessage>;

export const InboxThread = z.object({ messages: z.array(InboxMessage), hasMore: z.boolean() });
export type InboxThread = z.infer<typeof InboxThread>;
